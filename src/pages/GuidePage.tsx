import { useState } from "react"
import { useLocation, useNavigate } from "react-router-dom"
import { motion } from "framer-motion"
import {
  AlertTriangle, ArrowLeft, Check, CheckCircle2, CircleAlert, Clock3, Download,
  FileText, MessageSquareText, MoreHorizontal, Play, RotateCcw, ShieldCheck, Target,
} from "lucide-react"
import type { EvidenceLevel, InterviewGuide, ResumeSourceMetadata } from "@shared/guide"
import { QuestionCard } from "@/components/QuestionCard"
import { SectionHeader } from "@/components/SectionHeader"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import { Card } from "@/components/ui/card"
import type { SavedGenerationInput } from "@/pages/GenerateGuidePage"

interface GuideLocationState {
  generationInput?: SavedGenerationInput
  guide?: InterviewGuide
  source?: ResumeSourceMetadata
}

const evidenceTone: Record<EvidenceLevel, "success" | "info" | "warning" | "neutral"> = {
  strong: "success",
  moderate: "info",
  weak: "warning",
  missing: "neutral",
}

function titleCase(value: string) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function GuideError({ detail, onRetry }: { detail: string; onRetry: () => void }) {
  return (
    <div className="flex min-h-[calc(100vh-76px)] items-center justify-center px-4 py-10">
      <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="w-full max-w-lg rounded-3xl border border-line bg-white p-7 text-center shadow-float sm:p-9">
        <div className="mx-auto flex h-14 w-14 items-center justify-center rounded-2xl bg-warning-soft text-warning"><AlertTriangle className="h-7 w-7" /></div>
        <Badge variant="warning" className="mt-5">Generation paused</Badge>
        <h2 className="mt-4 text-2xl font-bold tracking-[-0.035em] text-ink">We couldn’t generate the guide right now.</h2>
        <p className="mx-auto mt-2 max-w-sm text-sm leading-6 text-muted">{detail}</p>
        <Button variant="brand" className="mt-6" onClick={onRetry}><RotateCcw className="h-4 w-4" /> Return to source documents</Button>
      </motion.div>
    </div>
  )
}

function GuideContent({ guide, sourceInput, source }: { guide: InterviewGuide; sourceInput?: SavedGenerationInput; source?: ResumeSourceMetadata }) {
  const navigate = useNavigate()
  const [showAllQuestions, setShowAllQuestions] = useState(false)
  const visibleQuestions = showAllQuestions ? guide.questions : guide.questions.slice(0, 4)
  const remainingQuestions = guide.questions.length - visibleQuestions.length
  const sourcePath = sourceInput?.candidateId ? `/generate?candidate=${sourceInput.candidateId}` : "/generate"

  return (
    <div className="mx-auto max-w-[1280px] px-4 py-7 sm:px-6 sm:py-9 xl:px-10">
      <div className="mb-5 flex items-center justify-between">
        <button onClick={() => navigate(sourcePath, { state: sourceInput ? { generationInput: sourceInput } : undefined })} className="focus-ring flex items-center gap-2 rounded-lg text-xs font-semibold text-muted transition-colors hover:text-ink"><ArrowLeft className="h-4 w-4" /> Source documents</button>
        <div className="flex items-center gap-2"><Button variant="outline" size="sm" className="hidden sm:flex"><Download className="h-3.5 w-3.5" /> Export</Button><Button variant="outline" size="icon" className="h-9 w-9" aria-label="More guide options"><MoreHorizontal className="h-4 w-4" /></Button></div>
      </div>

      <motion.section initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="overflow-hidden rounded-3xl bg-ink p-6 text-white shadow-card sm:p-8">
        <div className="flex flex-col justify-between gap-7 lg:flex-row lg:items-center">
          <div>
            <div className="flex flex-wrap gap-2"><Badge className="bg-brand text-ink"><CheckCircle2 className="h-3 w-3" /> Generated by Gemini</Badge>{source?.resumeSource === "pdf" && <Badge className="bg-white/10 text-neutral-100"><FileText className="h-3 w-3" /> PDF analysed by Gemini{source.resumeFileName ? ` · ${source.resumeFileName}` : ""}</Badge>}</div>
            <h2 className="mt-4 text-3xl font-bold tracking-[-0.04em] sm:text-4xl">Interview Guide</h2>
            <p className="mt-2 text-sm text-neutral-300">{guide.candidateName} <span className="mx-2 text-neutral-600">·</span> {guide.role}</p>
          </div>
          <div className="flex flex-wrap items-center gap-2 sm:gap-3">
            <div className="rounded-xl border border-white/10 bg-white/[0.06] px-4 py-3"><p className="text-[10px] uppercase tracking-[0.12em] text-neutral-400">Preparation</p><p className="mt-1 flex items-center gap-2 text-sm font-semibold"><Clock3 className="h-4 w-4 text-brand" />Guide ready</p></div>
            <Button variant="brand" size="lg"><Play className="h-4 w-4 fill-current" /> Start interview</Button>
          </div>
        </div>
      </motion.section>

      <section className="mt-7">
        <Card className="p-6 sm:p-7">
          <div className="grid gap-5 lg:grid-cols-[auto_1fr_auto] lg:items-start">
            <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-brand-soft text-brand-dark"><FileText className="h-5 w-5" /></div>
            <div><p className="text-[10px] font-bold uppercase tracking-[0.15em] text-brand-dark">Before you start</p><h2 className="mt-1 text-lg font-bold text-ink">Your 60-second briefing</h2><p className="mt-3 text-sm leading-6 text-secondary">{guide.summary}</p></div>
            <div className="rounded-xl bg-subtle px-4 py-3 text-center"><p className="text-xl font-bold text-ink">{guide.questions.length}</p><p className="text-[10px] font-semibold uppercase tracking-[0.1em] text-muted">Questions</p></div>
          </div>
        </Card>
      </section>

      <section className="mt-10">
        <SectionHeader eyebrow="Resume evidence" title="Strong areas to explore" description="Use these strengths to understand depth, ownership and judgment." />
        <div className="grid gap-4 lg:grid-cols-3">
          {guide.strengths.map((strength, index) => (
            <motion.div key={`${strength.area}-${index}`} initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: index * 0.05 }}>
              <Card className="h-full p-5"><div className="flex items-start justify-between gap-3"><div className="flex h-9 w-9 items-center justify-center rounded-xl bg-brand-soft text-brand-dark"><Check className="h-4 w-4" strokeWidth={3} /></div><Badge variant="success">Resume evidence</Badge></div><h3 className="mt-4 text-base font-bold text-ink">{strength.area}</h3><p className="mt-3 text-xs leading-5 text-secondary">{strength.evidence}</p></Card>
            </motion.div>
          ))}
        </div>
      </section>

      <section className="mt-10">
        <SectionHeader eyebrow="Role alignment" title="Requirement evidence map" description="How the role requirements connect to evidence in the resume." />
        <Card className="overflow-hidden"><div className="divide-y divide-line">
          {guide.requirementMatches.map((match, index) => (
            <div key={`${match.requirement}-${index}`} className="grid gap-3 p-5 sm:grid-cols-[minmax(180px,0.7fr)_minmax(0,1.3fr)_auto] sm:items-center sm:p-6"><p className="text-sm font-bold text-ink">{match.requirement}</p><p className="text-xs leading-5 text-secondary">{match.candidateEvidence}</p><Badge variant={evidenceTone[match.evidenceLevel]}>{titleCase(match.evidenceLevel)} evidence</Badge></div>
          ))}
        </div></Card>
      </section>

      <section className="mt-10">
        <SectionHeader eyebrow="Probe thoughtfully" title="Areas to validate" description="Evidence is limited here. Use the interview to build a clearer picture." />
        <div className="grid gap-4 lg:grid-cols-2">
          {guide.areasToValidate.map((area, index) => (
            <Card key={`${area.requirement}-${index}`} className="border-warning/20 p-5 sm:p-6">
              <div className="flex items-center gap-3"><div className="flex h-9 w-9 items-center justify-center rounded-xl bg-warning-soft text-warning"><CircleAlert className="h-[18px] w-[18px]" /></div><div><p className="text-[10px] font-bold uppercase tracking-[0.12em] text-warning">Requirement</p><h3 className="mt-0.5 text-sm font-bold text-ink">{area.requirement}</h3></div></div>
              <div className="mt-5 grid gap-3 sm:grid-cols-2"><div className="rounded-xl bg-subtle p-4"><p className="text-[10px] font-bold uppercase tracking-[0.12em] text-muted">Candidate evidence</p><p className="mt-2 text-xs leading-5 text-secondary">{area.candidateEvidence}</p></div><div className="rounded-xl bg-warning-soft/50 p-4"><p className="text-[10px] font-bold uppercase tracking-[0.12em] text-warning">Why validate</p><p className="mt-2 text-xs leading-5 text-secondary">{area.reason}</p></div></div>
            </Card>
          ))}
        </div>
      </section>

      <section className="mt-10">
        <SectionHeader eyebrow={`Personalised for ${guide.candidateName}`} title="Suggested interview questions" description="Open a question to see the evidence behind it and why it matters." action={<Badge variant="info"><MessageSquareText className="h-3 w-3" /> {guide.questions.length} questions</Badge>} />
        <div className="space-y-3">{visibleQuestions.map((question, index) => <QuestionCard key={question.id} question={question} number={index + 1} defaultOpen={index === 0} />)}</div>
        {remainingQuestions > 0 && <Button variant="outline" className="mt-4 w-full" onClick={() => setShowAllQuestions(true)}>Show {remainingQuestions} more {remainingQuestions === 1 ? "question" : "questions"}</Button>}
      </section>

      <section className="mt-8 flex flex-col items-start justify-between gap-4 rounded-2xl border border-line bg-subtle/60 p-5 sm:flex-row sm:items-center">
        <div className="flex items-start gap-3"><ShieldCheck className="mt-0.5 h-5 w-5 shrink-0 text-brand-dark" /><div><h3 className="text-sm font-bold text-ink">You make the hiring decision</h3><p className="mt-1 max-w-2xl text-xs leading-5 text-muted">This guide organises evidence and suggests questions. It does not score the candidate or recommend an outcome.</p></div></div>
        <Button variant="ghost" size="sm"><Target className="h-4 w-4" /> Interview principles</Button>
      </section>
    </div>
  )
}

export function GuidePage() {
  const navigate = useNavigate()
  const location = useLocation()
  const state = (location.state ?? {}) as GuideLocationState
  const guide = state.guide ?? null
  const sourcePath = state.generationInput?.candidateId ? `/generate?candidate=${state.generationInput.candidateId}` : "/generate"

  if (!guide) return <GuideError detail="No live Gemini guide was found. Return to the source documents and generate one from a resume and job description." onRetry={() => navigate(sourcePath, { state: state.generationInput ? { generationInput: state.generationInput } : undefined })} />
  return <GuideContent guide={guide} sourceInput={state.generationInput} source={state.source} />
}
